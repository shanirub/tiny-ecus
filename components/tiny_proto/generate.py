#!/usr/bin/env python3
"""Generate tiny_proto.c and include/tiny_proto.h from tiny_proto.dbc.

The DBC is the single source of the CAN frame layout; the C files are
generated from it with cantools and committed, so the firmware build needs no
Python. Never edit the generated files by hand: change the DBC and run

    python3 components/tiny_proto/generate.py

`--check` regenerates in memory and exits non-zero if the committed files
differ (CI runs this). cantools' own header line carries a timestamp, which
would make every run differ; it is replaced by a fixed line.

Needs cantools at the version pinned in tools/requirements-test.txt.
"""

import argparse
import pathlib
import re
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
DBC = HERE / "tiny_proto.dbc"
OUTPUTS = {
    "tiny_proto.h": HERE / "include" / "tiny_proto.h",
    "tiny_proto.c": HERE / "tiny_proto.c",
}
# e.g. " * @brief This header file was generated by cantools version 45.1.2 Wed Nov  4 20:45:17 2026."
STAMP = re.compile(r"(was generated by cantools version \S+) .*\.$", re.MULTILINE)


def generate() -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            [sys.executable, "-m", "cantools", "generate_c_source",
             "--no-floating-point-numbers",
             "--database-name", "tiny_proto",
             "--output-directory", tmp,
             str(DBC)],
            check=True, stdout=subprocess.DEVNULL)
        out = {}
        for name in OUTPUTS:
            text = (pathlib.Path(tmp) / name).read_text()
            text, n = STAMP.subn(r"\1 from tiny_proto.dbc. Do not edit: run generate.py.", text)
            if n != 1:
                sys.exit(f"{name}: expected one cantools header line, found {n}")
            out[name] = text
        return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="compare with the committed files instead of writing them")
    args = parser.parse_args()

    stale = []
    for name, text in generate().items():
        path = OUTPUTS[name]
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(HERE.parents[1]))
        else:
            path.write_text(text)
    if stale:
        print("out of date with tiny_proto.dbc (run components/tiny_proto/generate.py):",
              *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
